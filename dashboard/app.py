# INVENTORY HELPERS
# ============================================================

def calculate_remaining_stock(
    normalized_restock,
    normalized_history
):
    """
    Estimate remaining available stock.

    Visuelle 2.0 forecasting values are normalized.

    Normalization scalar = 53

    Actual units = normalized value * 53

    Historical legitimate sales are deducted from
    the normalized restock allocation.
    """

    try:
        normalized_restock = float(
            normalized_restock
        )

    except (TypeError, ValueError):
        return 0.0

    if not np.isfinite(
        normalized_restock
    ):
        return 0.0

    normalized_restock = max(
        normalized_restock,
        0.0
    )

    normalized_history = np.asarray(
        normalized_history,
        dtype=float
    )

    normalized_history = np.nan_to_num(
        normalized_history,
        nan=0.0,
        posinf=0.0,
        neginf=0.0
    )

    normalized_history = np.maximum(
        normalized_history,
        0.0
    )

    cumulative_sales = 0.0

    for sales in normalized_history:

        sales = float(sales)

        if (
            cumulative_sales + sales
            <= normalized_restock
        ):

            cumulative_sales += sales

        else:

            remaining = max(
                normalized_restock
                - cumulative_sales,
                0.0
            )

            cumulative_sales += remaining

            break

    remaining_normalized = max(
        normalized_restock
        - cumulative_sales,
        0.0
    )

    remaining_units = float(
        inverse_transform(
            remaining_normalized
        )
    )

    return max(
        remaining_units,
        0.0
    )


