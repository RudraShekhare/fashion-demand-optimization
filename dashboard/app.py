# HISTORICAL RESTOCK SUMMARY
# ============================================================

def build_restock_summary(restocks):
    """
    Build historical restock statistics.

    IMPORTANT:
    restocks.csv -> qty is already actual units.

    DO NOT multiply qty by 53.
    """

    summary = (
        restocks
        .groupby(
            [
                "external_code",
                "retail",
            ],
            as_index=False,
        )
        .agg(
            total_restock_units=(
                "qty",
                "sum",
            ),
            restock_events=(
                "qty",
                "count",
            ),
            average_restock_units=(
                "qty",
                "mean",
            ),
        )
    )

    return summary


# ============================================================
# PRODUCT RESTOCK HISTORY
# ============================================================

def get_product_restock_history(
    restocks,
    external_code,
    retail,
):
    """
    Return historical restock events for a
    product-store combination.
    """

    result = restocks[
        (
            restocks["external_code"]
            == external_code
        )
        &
        (
            restocks["retail"]
            == retail
        )
    ].copy()

    if result.empty:
        return result

    result["restock_units"] = (
        pd.to_numeric(
            result["qty"],
            errors="coerce",
        )
        .fillna(0.0)
    )

    return result.sort_values(
        [
            "year",
            "week",
        ],
        ascending=False,
    )


